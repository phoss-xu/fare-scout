import {test} from 'node:test';
import assert from 'node:assert/strict';
import {pbkdf2Sync} from 'node:crypto';
import {harness,request,register} from './harness.mjs';
test('legacy password hashes, session rotation, CSRF, cross-origin and account isolation',async t=>{
  const h=await harness();t.after(()=>h.close());
  const salt='00112233445566778899aabbccddeeff';
  const hash='pbkdf2_sha256$600000$'+salt+'$'+pbkdf2Sync('旧账号密码',Buffer.from(salt,'hex'),600000,32,'sha256').toString('hex');
  await h.db.prepare("INSERT INTO users(email,name,password_hash,notification_email,created_at) VALUES('legacy@example.test','legacy',?,'legacy@example.test','2026-11-01')").bind(hash).run();
  const a={};assert.equal((await request(h,'/api/auth/login',{email:'legacy@example.test',password:'旧账号密码'},a)).status,200);
  const old={...a};assert.equal((await request(h,'/api/auth/login',{email:'legacy@example.test',password:'旧账号密码'},a)).status,200);
  assert.equal((await request(h,'/api/auth/session',undefined,old)).data.user,null);
  assert.equal((await request(h,'/api/email',{recipient:'new@example.test'},{cookie:a.cookie})).status,403);
  assert.equal((await request(h,'/api/email',{recipient:'new@example.test'},a,{Origin:'https://other.test'})).status,403);
  assert.equal((await request(h,'/api/email',{recipient:'new@example.test'},a)).status,200);
  const b=await register(h,'second@example.test');
  assert.equal((await request(h,'/api/state',undefined,b)).data.email.recipient,'second@example.test');
  assert.equal((await request(h,'/api/auth/login',{email:'absent@example.test',password:'wrong'})).status,401);
  const secure=await h.mf.dispatchFetch('https://localhost/api/auth/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({email:'legacy@example.test',password:'旧账号密码'})});
  assert.equal(secure.status,200);assert.match(secure.headers.get('Set-Cookie'),/; Secure/);assert.match(secure.headers.get('Set-Cookie'),/HttpOnly/);
  const remembered=await request(h,'/api/auth/login',{email:'legacy@example.test',password:'旧账号密码',remember:true});
  assert.equal(remembered.status,200);assert.match(remembered.response.headers.get('Set-Cookie'),/Max-Age=2592000/);
  const ordinary=await request(h,'/api/auth/login',{email:'legacy@example.test',password:'旧账号密码',remember:false});
  assert.equal(ordinary.status,200);assert.match(ordinary.response.headers.get('Set-Cookie'),/Max-Age=604800/);
  assert.equal((await request(h,'/api/auth/logout',{},a)).status,200);
  assert.equal((await request(h,'/api/state',undefined,a)).status,401);
});
test('single-use activation and persistent throttling',async t=>{
  const h=await harness();t.after(()=>h.close());
  const {createHash}=await import('node:crypto');
  const digest=createHash('sha256').update('local-setup-token').digest('hex');
  await h.db.prepare("INSERT INTO users(id,email,name,notification_email,created_at) VALUES(1,'activate@example.test','test','activate@example.test','now')").run();
  await h.db.prepare('INSERT INTO setup_tokens VALUES(?,1,?)').bind(digest,Date.now()/1000+3600).run();
  const r=await request(h,'/api/auth/activate',{token:'local-setup-token',password:'activate-pass'});
  assert.equal(r.status,200);
  assert.equal((await request(h,'/api/auth/activate',{token:'local-setup-token',password:'another-pass'})).status,400);
  await h.db.prepare("INSERT INTO auth_limits VALUES(?,10,?)").bind(createHash('sha256').update('account:blocked@example.test').digest('hex'),Date.now()/1000).run();
  assert.equal((await request(h,'/api/auth/login',{email:'blocked@example.test',password:'wrong'})).status,429);
  const malformed=await h.mf.dispatchFetch('http://localhost/api/auth/register',{method:'POST',headers:{'Content-Type':'application/json'},body:'{'});
  assert.equal(malformed.status,400);
  const huge=await h.mf.dispatchFetch('http://localhost/api/auth/register',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({text:'x'.repeat(17000)})});
  assert.equal(huge.status,413);
});
